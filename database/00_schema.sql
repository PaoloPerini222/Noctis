-- =====================================================
-- ESQUEMA DEFINITIVO - Sistema de eventos
-- Crea todas las tablas, restricciones, funciones y triggers.
-- No carga datos: los catálogos van en 01_ y los datos de prueba en 02_.
-- Las tablas están ordenadas por dependencia (cada una solo referencia
-- tablas creadas antes), así las claves foráneas se declaran en la misma tabla.
-- =====================================================

BEGIN;

-- =====================================================
-- 1. EMPRESAS (los clientes de la plataforma)
-- Cada empresa es una organizadora con sus propios datos: el sistema es multiempresa.
-- Las administra el superadmin, que no pertenece a ninguna.
-- =====================================================

CREATE TABLE public.empresas (
    id_empresa serial NOT NULL,
    nombre character varying(150) NOT NULL,
    cuit character varying(13) NOT NULL,
    email character varying(150),
    telefono character varying(30),
    direccion character varying(200),
    activo boolean DEFAULT true,
    fecha_creacion timestamp without time zone DEFAULT now(),
    -- Link público de reservas de la empresa (/reservar/<token>).
    token_reservas uuid NOT NULL DEFAULT gen_random_uuid(),
    CONSTRAINT empresas_pkey PRIMARY KEY (id_empresa),
    CONSTRAINT empresas_cuit_key UNIQUE (cuit),
    CONSTRAINT empresas_token_reservas_key UNIQUE (token_reservas)
);

-- =====================================================
-- 2. ACCESO Y PERSONAL
-- =====================================================

-- Credenciales de acceso (auth propio con JWT). La contraseña se guarda hasheada con bcrypt.
CREATE TABLE public.usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email character varying(150) NOT NULL,
    password_hash character varying(100) NOT NULL,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT usuario_pkey PRIMARY KEY (id_usuario),
    CONSTRAINT usuario_email_key UNIQUE (email)
);

-- Catálogo de roles: admin (quien usa el sistema en una empresa) y superadmin (los dueños del sistema).
CREATE TABLE public.rol (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(30) NOT NULL,
    CONSTRAINT rol_pkey PRIMARY KEY (id_rol),
    CONSTRAINT rol_nombre_key UNIQUE (nombre)
);

-- Personas de una empresa. Cada una puede tener un usuario para ingresar al sistema.
-- id_empresa es NULL solo para el equipo de la plataforma (superadmin).
CREATE TABLE public.personal (
    id_personal integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100),
    telefono character varying(30),
    email_contacto character varying(150),
    nombre_completo character varying(201) GENERATED ALWAYS AS (nombre || COALESCE(' ' || apellido, '')) STORED,
    usuario_id integer,
    id_empresa integer,
    CONSTRAINT personal_pkey PRIMARY KEY (id_personal),
    CONSTRAINT personal_usuario_id_key UNIQUE (usuario_id),
    CONSTRAINT personal_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT personal_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa)
);

-- Roles de cada persona (muchos a muchos).
CREATE TABLE public.personal_rol (
    id_personal integer NOT NULL,
    id_rol integer NOT NULL,
    CONSTRAINT personal_rol_pkey PRIMARY KEY (id_personal, id_rol),
    CONSTRAINT personal_rol_id_personal_fkey FOREIGN KEY (id_personal) REFERENCES public.personal(id_personal),
    CONSTRAINT personal_rol_id_rol_fkey FOREIGN KEY (id_rol) REFERENCES public.rol(id_rol)
);

-- =====================================================
-- 3. CLIENTES Y EVENTOS
-- Todo lo que cuelga de una empresa lleva id_empresa: cada empresa solo ve y toca lo suyo.
-- =====================================================

-- Teléfono obligatorio, email opcional.
-- confirmado: quien reserva por el link público entra en false y pasa a ser cliente (true) cuando se acepta su reserva.
-- Los que carga el admin a mano ya son clientes.
CREATE TABLE public.cliente (
    id_cliente integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100),
    nombre_completo character varying(201) GENERATED ALWAYS AS (nombre || COALESCE(' ' || apellido, '')) STORED,
    telefono character varying(30),
    email character varying(100),
    direccion character varying(200),
    id_empresa integer NOT NULL,
    confirmado boolean NOT NULL DEFAULT true,
    CONSTRAINT cliente_pkey PRIMARY KEY (id_cliente),
    CONSTRAINT cliente_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa),
    CONSTRAINT chk_cliente_telefono CHECK (NULLIF(TRIM(BOTH FROM telefono), '') IS NOT NULL)
);

-- Salones o lugares de la empresa donde se hacen los eventos (el cliente elige uno al reservar).
CREATE TABLE public.sucursal (
    id_sucursal integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    direccion character varying(200),
    id_empresa integer NOT NULL,
    CONSTRAINT sucursal_pkey PRIMARY KEY (id_sucursal),
    CONSTRAINT sucursal_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa)
);

-- Una reserva entra como "propuesta"; si la organizadora la acepta queda "confirmado".
-- La fecha se exige para confirmar (ver trigger trg_validar_evento_confirmado).
-- id_sucursal: el salón del evento (la fecha se bloquea por salón).
CREATE TABLE public.evento (
    id_evento integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cliente integer NOT NULL,
    tipo_evento character varying(50) NOT NULL,
    fecha date,
    sede_prevista character varying(100),
    cant_asistentes_estimada integer,
    necesidades_preferencias character varying(500),
    estado character varying(20) NOT NULL DEFAULT 'propuesta',
    id_organizador integer,
    estado_sede character varying(15) NOT NULL DEFAULT 'pendiente',
    token_publico uuid NOT NULL DEFAULT gen_random_uuid(),
    id_empresa integer NOT NULL,
    id_sucursal integer,
    CONSTRAINT evento_pkey PRIMARY KEY (id_evento),
    CONSTRAINT evento_id_sucursal_fkey FOREIGN KEY (id_sucursal) REFERENCES public.sucursal(id_sucursal),
    CONSTRAINT evento_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa),
    CONSTRAINT evento_token_publico_key UNIQUE (token_publico),
    CONSTRAINT fk_evento_id_cliente_cliente FOREIGN KEY (id_cliente) REFERENCES public.cliente(id_cliente),
    CONSTRAINT evento_id_organizador_fkey FOREIGN KEY (id_organizador) REFERENCES public.personal(id_personal),
    CONSTRAINT chk_evento_estado CHECK (estado IN ('propuesta', 'confirmado', 'rechazado', 'realizado', 'cancelado')),
    CONSTRAINT chk_evento_estado_sede CHECK (estado_sede IN ('pendiente', 'confirmada', 'no_disponible'))
);

-- Historial de cambios del evento.
CREATE TABLE public.cambio_evento (
    id_cambio integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento integer NOT NULL,
    fecha_registro timestamp with time zone NOT NULL DEFAULT now(),
    tipo_cambio character varying(50) NOT NULL,
    descripcion character varying(500) NOT NULL,
    registrado_por integer NOT NULL,
    situacion_compromisos character varying(500),
    CONSTRAINT cambio_evento_pkey PRIMARY KEY (id_cambio),
    CONSTRAINT cambio_evento_id_evento_fkey FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento) ON DELETE CASCADE,
    CONSTRAINT cambio_evento_registrado_por_fkey FOREIGN KEY (registrado_por) REFERENCES public.personal(id_personal)
);

-- =====================================================
-- 4. SERVICIOS Y PROVEEDORES
-- =====================================================

-- Lo que ve el cliente en el link de reservas: descripción, equipamiento con el que se presta y precio.
CREATE TABLE public.servicio (
    id_servicio integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    descripcion character varying(255),
    id_empresa integer NOT NULL,
    precio numeric(10,2),
    equipamiento character varying(500),
    CONSTRAINT servicio_pkey PRIMARY KEY (id_servicio),
    CONSTRAINT servicio_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa),
    CONSTRAINT chk_servicio_precio CHECK (precio IS NULL OR precio >= 0)
);

-- Teléfono obligatorio, email opcional.
CREATE TABLE public.proveedor (
    id_proveedor integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    contacto character varying(100),
    telefono character varying(30),
    email character varying(100),
    direccion character varying(200),
    id_empresa integer NOT NULL,
    CONSTRAINT proveedor_pkey PRIMARY KEY (id_proveedor),
    CONSTRAINT proveedor_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa),
    CONSTRAINT chk_proveedor_telefono CHECK (NULLIF(TRIM(BOTH FROM telefono), '') IS NOT NULL)
);

-- Servicios que ofrece cada proveedor (muchos a muchos).
CREATE TABLE public.proveedor_servicio (
    id_proveedor integer NOT NULL,
    id_servicio integer NOT NULL,
    CONSTRAINT proveedor_servicio_pkey PRIMARY KEY (id_proveedor, id_servicio),
    CONSTRAINT fk_proveedor_servicio_id_proveedor_proveedor FOREIGN KEY (id_proveedor) REFERENCES public.proveedor(id_proveedor),
    CONSTRAINT fk_proveedor_servicio_id_servicio_servicio FOREIGN KEY (id_servicio) REFERENCES public.servicio(id_servicio)
);

-- Servicios que el cliente eligió al reservar, con el precio de ese momento
-- (si después cambia el precio del servicio, la reserva conserva el suyo).
CREATE TABLE public.evento_servicio (
    id_evento integer NOT NULL,
    id_servicio integer NOT NULL,
    precio numeric(10,2),
    CONSTRAINT evento_servicio_pkey PRIMARY KEY (id_evento, id_servicio),
    CONSTRAINT evento_servicio_id_evento_fkey FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento) ON DELETE CASCADE,
    CONSTRAINT evento_servicio_id_servicio_fkey FOREIGN KEY (id_servicio) REFERENCES public.servicio(id_servicio)
);

-- A qué proveedor se le consultó por cada servicio de la reserva y qué contestó
-- (avisado = se le mandó la consulta y falta su respuesta). La reserva solo se acepta cuando cada servicio
-- que tiene proveedores cuenta con uno disponible.
CREATE TABLE public.evento_proveedor (
    id_evento integer NOT NULL,
    id_servicio integer NOT NULL,
    id_proveedor integer NOT NULL,
    estado character varying(15) NOT NULL DEFAULT 'avisado',
    avisado_en timestamp with time zone NOT NULL DEFAULT now(),
    respondido_en timestamp with time zone,
    CONSTRAINT evento_proveedor_pkey PRIMARY KEY (id_evento, id_servicio, id_proveedor),
    CONSTRAINT evento_proveedor_id_evento_fkey FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento) ON DELETE CASCADE,
    CONSTRAINT evento_proveedor_id_servicio_fkey FOREIGN KEY (id_servicio) REFERENCES public.servicio(id_servicio),
    CONSTRAINT evento_proveedor_id_proveedor_fkey FOREIGN KEY (id_proveedor) REFERENCES public.proveedor(id_proveedor) ON DELETE CASCADE,
    CONSTRAINT chk_evento_proveedor_estado CHECK (estado IN ('avisado', 'disponible', 'no_disponible'))
);

-- Todas las consultas filtran por empresa.
CREATE INDEX personal_id_empresa_idx ON public.personal (id_empresa);
CREATE INDEX cliente_id_empresa_idx ON public.cliente (id_empresa);
CREATE INDEX evento_id_empresa_idx ON public.evento (id_empresa);
CREATE INDEX servicio_id_empresa_idx ON public.servicio (id_empresa);
CREATE INDEX proveedor_id_empresa_idx ON public.proveedor (id_empresa);
CREATE INDEX sucursal_id_empresa_idx ON public.sucursal (id_empresa);

-- Una reserva por día por salón: una fecha con un evento en curso o realizado no se vuelve a reservar en ese salón
-- (los eventos sin salón cuentan como un mismo lugar).
CREATE UNIQUE INDEX evento_fecha_ocupada_idx ON public.evento (id_empresa, COALESCE(id_sucursal, 0), fecha)
    WHERE fecha IS NOT NULL AND estado IN ('propuesta', 'confirmado', 'realizado');

-- =====================================================
-- 5. REGLAS DE NEGOCIO (funciones y triggers)
-- =====================================================

-- Exige la fecha para confirmar el evento (la sede y los asistentes son opcionales).
CREATE FUNCTION public.validar_evento_confirmado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado IN ('confirmado', 'realizado') AND NEW.fecha IS NULL THEN
        RAISE EXCEPTION 'Para confirmar el evento se requiere la fecha.';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_evento_confirmado
BEFORE INSERT OR UPDATE OF estado, fecha
ON public.evento
FOR EACH ROW
EXECUTE FUNCTION public.validar_evento_confirmado();

COMMIT;

-- =====================================================
-- ESQUEMA DEFINITIVO - Sistema de eventos
-- Crea todas las tablas, restricciones, funciones y triggers.
-- No carga datos: los catálogos van en 01_ y los datos de prueba en 02_.
-- Las tablas están ordenadas por dependencia (cada una solo referencia
-- tablas creadas antes), así las claves foráneas se declaran en la misma tabla.
-- =====================================================

BEGIN;

-- =====================================================
-- 1. EMPRESAS (los clientes de la plataforma)
-- Cada empresa es una organizadora con sus propios datos: el sistema es multiempresa.
-- Las administra el superadmin, que no pertenece a ninguna.
-- =====================================================

CREATE TABLE public.empresas (
    id_empresa serial NOT NULL,
    nombre character varying(150) NOT NULL,
    cuit character varying(13) NOT NULL,
    email character varying(150),
    telefono character varying(30),
    direccion character varying(200),
    activo boolean DEFAULT true,
    fecha_creacion timestamp without time zone DEFAULT now(),
    CONSTRAINT empresas_pkey PRIMARY KEY (id_empresa),
    CONSTRAINT empresas_cuit_key UNIQUE (cuit)
);

-- =====================================================
-- 2. ACCESO Y PERSONAL
-- =====================================================

-- Credenciales de acceso (auth propio con JWT). La contraseña se guarda hasheada con bcrypt.
CREATE TABLE public.usuario (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email character varying(150) NOT NULL,
    password_hash character varying(100) NOT NULL,
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT usuario_pkey PRIMARY KEY (id_usuario),
    CONSTRAINT usuario_email_key UNIQUE (email)
);

-- Catálogo de roles (responsable, organizador, coordinador y superadmin, que es de la plataforma).
CREATE TABLE public.rol (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(30) NOT NULL,
    CONSTRAINT rol_pkey PRIMARY KEY (id_rol),
    CONSTRAINT rol_nombre_key UNIQUE (nombre)
);

-- Personas de una empresa. Cada una puede tener un usuario para ingresar al sistema.
-- id_empresa es NULL solo para el equipo de la plataforma (superadmin).
CREATE TABLE public.personal (
    id_personal integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100),
    telefono character varying(30),
    email_contacto character varying(150),
    nombre_completo character varying(201) GENERATED ALWAYS AS (nombre || COALESCE(' ' || apellido, '')) STORED,
    usuario_id integer,
    id_empresa integer,
    CONSTRAINT personal_pkey PRIMARY KEY (id_personal),
    CONSTRAINT personal_usuario_id_key UNIQUE (usuario_id),
    CONSTRAINT personal_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    CONSTRAINT personal_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa)
);

-- Roles de cada persona (muchos a muchos).
CREATE TABLE public.personal_rol (
    id_personal integer NOT NULL,
    id_rol integer NOT NULL,
    CONSTRAINT personal_rol_pkey PRIMARY KEY (id_personal, id_rol),
    CONSTRAINT personal_rol_id_personal_fkey FOREIGN KEY (id_personal) REFERENCES public.personal(id_personal),
    CONSTRAINT personal_rol_id_rol_fkey FOREIGN KEY (id_rol) REFERENCES public.rol(id_rol)
);

-- =====================================================
-- 3. CLIENTES Y EVENTOS
-- Todo lo que cuelga de una empresa lleva id_empresa: cada empresa solo ve y toca lo suyo.
-- =====================================================

-- Teléfono obligatorio, email opcional.
CREATE TABLE public.cliente (
    id_cliente integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    apellido character varying(100),
    nombre_completo character varying(201) GENERATED ALWAYS AS (nombre || COALESCE(' ' || apellido, '')) STORED,
    telefono character varying(30),
    email character varying(100),
    direccion character varying(200),
    id_empresa integer NOT NULL,
    CONSTRAINT cliente_pkey PRIMARY KEY (id_cliente),
    CONSTRAINT cliente_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa),
    CONSTRAINT chk_cliente_telefono CHECK (NULLIF(TRIM(BOTH FROM telefono), '') IS NOT NULL)
);

-- La fecha puede estar pendiente al recibir la solicitud; se exige al aceptar o confirmar
-- (ver trigger trg_validar_evento_confirmado).
CREATE TABLE public.evento (
    id_evento integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cliente integer NOT NULL,
    tipo_evento character varying(50) NOT NULL,
    fecha date,
    sede_prevista character varying(100),
    cant_asistentes_estimada integer,
    necesidades_preferencias character varying(500),
    estado character varying(20) NOT NULL DEFAULT 'recibida',
    id_organizador integer,
    estado_sede character varying(15) NOT NULL DEFAULT 'pendiente',
    token_publico uuid NOT NULL DEFAULT gen_random_uuid(),
    id_empresa integer NOT NULL,
    CONSTRAINT evento_pkey PRIMARY KEY (id_evento),
    CONSTRAINT evento_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa),
    CONSTRAINT evento_token_publico_key UNIQUE (token_publico),
    CONSTRAINT fk_evento_id_cliente_cliente FOREIGN KEY (id_cliente) REFERENCES public.cliente(id_cliente),
    CONSTRAINT evento_id_organizador_fkey FOREIGN KEY (id_organizador) REFERENCES public.personal(id_personal),
    CONSTRAINT chk_evento_estado CHECK (estado IN (
        'recibida', 'en_evaluacion', 'propuesta_enviada', 'aceptada', 'rechazada',
        'confirmado', 'preparacion', 'realizado', 'cancelado'
    )),
    CONSTRAINT chk_evento_estado_sede CHECK (estado_sede IN ('pendiente', 'confirmada'))
);

-- Historial de cambios del evento.
CREATE TABLE public.cambio_evento (
    id_cambio integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento integer NOT NULL,
    fecha_registro timestamp with time zone NOT NULL DEFAULT now(),
    tipo_cambio character varying(50) NOT NULL,
    descripcion character varying(500) NOT NULL,
    registrado_por integer NOT NULL,
    situacion_compromisos character varying(500),
    CONSTRAINT cambio_evento_pkey PRIMARY KEY (id_cambio),
    CONSTRAINT cambio_evento_id_evento_fkey FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento),
    CONSTRAINT cambio_evento_registrado_por_fkey FOREIGN KEY (registrado_por) REFERENCES public.personal(id_personal)
);

-- =====================================================
-- 4. SERVICIOS Y PROVEEDORES
-- =====================================================

CREATE TABLE public.servicio (
    id_servicio integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    descripcion character varying(255),
    id_empresa integer NOT NULL,
    CONSTRAINT servicio_pkey PRIMARY KEY (id_servicio),
    CONSTRAINT servicio_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa)
);

CREATE TABLE public.proveedor (
    id_proveedor integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    contacto character varying(100),
    telefono character varying(30),
    email character varying(100),
    direccion character varying(200),
    id_empresa integer NOT NULL,
    CONSTRAINT proveedor_pkey PRIMARY KEY (id_proveedor),
    CONSTRAINT proveedor_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa)
);

-- Servicios que ofrece cada proveedor (muchos a muchos).
CREATE TABLE public.proveedor_servicio (
    id_proveedor integer NOT NULL,
    id_servicio integer NOT NULL,
    CONSTRAINT proveedor_servicio_pkey PRIMARY KEY (id_proveedor, id_servicio),
    CONSTRAINT fk_proveedor_servicio_id_proveedor_proveedor FOREIGN KEY (id_proveedor) REFERENCES public.proveedor(id_proveedor),
    CONSTRAINT fk_proveedor_servicio_id_servicio_servicio FOREIGN KEY (id_servicio) REFERENCES public.servicio(id_servicio)
);

-- Servicios que el cliente excluyó explícitamente de un evento.
CREATE TABLE public.servicio_excluido_evento (
    id_exclusion integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento integer NOT NULL,
    id_servicio integer NOT NULL,
    motivo character varying(500),
    registrado_por integer NOT NULL,
    fecha_registro timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT servicio_excluido_evento_pkey PRIMARY KEY (id_exclusion),
    CONSTRAINT servicio_excluido_evento_id_evento_id_servicio_key UNIQUE (id_evento, id_servicio),
    CONSTRAINT servicio_excluido_evento_id_evento_fkey FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento),
    CONSTRAINT servicio_excluido_evento_id_servicio_fkey FOREIGN KEY (id_servicio) REFERENCES public.servicio(id_servicio),
    CONSTRAINT servicio_excluido_evento_registrado_por_fkey FOREIGN KEY (registrado_por) REFERENCES public.personal(id_personal)
);

-- =====================================================
-- 5. PROPUESTAS
-- =====================================================

-- Una propuesta por evento. Si se modifica estando aprobada o enviada,
-- vuelve a pendiente_aprobacion (ver trigger trg_reabrir_propuesta_modificada).
CREATE TABLE public.propuesta (
    id_propuesta integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento integer NOT NULL,
    fecha_emision date,
    total numeric(10,2) DEFAULT 0,
    estado character varying(20) NOT NULL DEFAULT 'borrador',
    fecha_respuesta date,
    condiciones_acordadas character varying(500),
    aprobado_por integer,
    fecha_aprobacion timestamp with time zone,
    motivo_rechazo character varying(500),
    CONSTRAINT propuesta_pkey PRIMARY KEY (id_propuesta),
    CONSTRAINT propuesta_id_evento_key UNIQUE (id_evento),
    CONSTRAINT fk_propuesta_id_evento_evento FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento),
    CONSTRAINT propuesta_aprobado_por_fkey FOREIGN KEY (aprobado_por) REFERENCES public.personal(id_personal),
    CONSTRAINT chk_propuesta_estado CHECK (estado IN (
        'borrador', 'pendiente_aprobacion', 'aprobada', 'enviada',
        'en_negociacion', 'aceptada', 'rechazada'
    ))
);

-- Servicios incluidos en la propuesta. "descartado" marca un servicio evaluado
-- que el cliente no quiso; id_proveedor_anterior registra reemplazos de proveedor.
CREATE TABLE public.detalle_propuesta (
    id_detalle integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_propuesta integer NOT NULL,
    id_servicio integer NOT NULL,
    id_proveedor integer,
    cantidad integer NOT NULL DEFAULT 1,
    importe_unitario numeric(10,2) NOT NULL,
    estado_proveedor character varying(20) NOT NULL DEFAULT 'pendiente',
    descartado boolean NOT NULL DEFAULT false,
    id_proveedor_anterior integer,
    observaciones character varying(500),
    CONSTRAINT detalle_propuesta_pkey PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_propuesta_id_propuesta_propuesta FOREIGN KEY (id_propuesta) REFERENCES public.propuesta(id_propuesta),
    CONSTRAINT fk_detalle_propuesta_id_servicio_servicio FOREIGN KEY (id_servicio) REFERENCES public.servicio(id_servicio),
    CONSTRAINT fk_detalle_propuesta_id_proveedor_proveedor FOREIGN KEY (id_proveedor) REFERENCES public.proveedor(id_proveedor),
    CONSTRAINT detalle_propuesta_id_proveedor_anterior_fkey FOREIGN KEY (id_proveedor_anterior) REFERENCES public.proveedor(id_proveedor),
    CONSTRAINT chk_detalle_estado_proveedor CHECK (estado_proveedor IN ('pendiente', 'confirmado', 'no_disponible'))
);

-- =====================================================
-- 6. TAREAS
-- =====================================================

-- "Vencida" no se guarda: se calcula en la consulta
-- (fecha_prevista < CURRENT_DATE AND estado <> 'terminada').
CREATE TABLE public.tarea (
    id_tarea integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento integer NOT NULL,
    id_personal integer NOT NULL,
    descripcion character varying(255) NOT NULL,
    fecha_prevista date,
    estado character varying(20) NOT NULL DEFAULT 'pendiente',
    id_detalle integer,
    CONSTRAINT tarea_pkey PRIMARY KEY (id_tarea),
    CONSTRAINT fk_tarea_id_evento_evento FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento),
    CONSTRAINT fk_tarea_id_personal_personal FOREIGN KEY (id_personal) REFERENCES public.personal(id_personal),
    CONSTRAINT tarea_id_detalle_fkey FOREIGN KEY (id_detalle) REFERENCES public.detalle_propuesta(id_detalle),
    CONSTRAINT chk_tarea_estado CHECK (estado IN ('pendiente', 'en_curso', 'terminada', 'cancelada')),
    CONSTRAINT chk_tarea_fecha_prevista CHECK (fecha_prevista IS NOT NULL)
);

-- =====================================================
-- 7. CIERRE DEL EVENTO Y AVISOS A PROVEEDORES
-- =====================================================

CREATE TABLE public.cierre (
    id_cierre integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento integer NOT NULL,
    fecha date NOT NULL,
    resultado character varying(20) NOT NULL,
    observaciones character varying(255),
    motivo_cancelacion character varying(500),
    registrado_por integer,
    origen_cancelacion character varying(15),
    CONSTRAINT cierre_pkey PRIMARY KEY (id_cierre),
    CONSTRAINT cierre_id_evento_key UNIQUE (id_evento),
    CONSTRAINT fk_cierre_id_evento_evento FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento),
    CONSTRAINT cierre_registrado_por_fkey FOREIGN KEY (registrado_por) REFERENCES public.personal(id_personal),
    CONSTRAINT chk_cierre_resultado CHECK (resultado IN ('realizado', 'cancelado')),
    CONSTRAINT chk_cierre_origen_cancelacion CHECK (origen_cancelacion IS NULL OR origen_cancelacion IN ('cliente', 'organizadora'))
);

-- Avisos a proveedores cuando se cancela un evento
-- (pendiente de decidir con el cliente/grupo si se usa).
CREATE TABLE public.aviso_proveedor_cancelacion (
    id_aviso integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_cierre integer NOT NULL,
    id_proveedor integer NOT NULL,
    fecha_aviso timestamp with time zone,
    medio character varying(30),
    estado character varying(20) NOT NULL DEFAULT 'pendiente',
    observaciones character varying(500),
    registrado_por integer,
    CONSTRAINT aviso_proveedor_cancelacion_pkey PRIMARY KEY (id_aviso),
    CONSTRAINT aviso_proveedor_cancelacion_id_cierre_fkey FOREIGN KEY (id_cierre) REFERENCES public.cierre(id_cierre),
    CONSTRAINT aviso_proveedor_cancelacion_id_proveedor_fkey FOREIGN KEY (id_proveedor) REFERENCES public.proveedor(id_proveedor),
    CONSTRAINT aviso_proveedor_cancelacion_registrado_por_fkey FOREIGN KEY (registrado_por) REFERENCES public.personal(id_personal),
    CONSTRAINT chk_aviso_estado CHECK (estado IN ('pendiente', 'enviado', 'confirmado', 'fallido'))
);

-- Todas las consultas filtran por empresa.
CREATE INDEX personal_id_empresa_idx ON public.personal (id_empresa);
CREATE INDEX cliente_id_empresa_idx ON public.cliente (id_empresa);
CREATE INDEX evento_id_empresa_idx ON public.evento (id_empresa);
CREATE INDEX servicio_id_empresa_idx ON public.servicio (id_empresa);
CREATE INDEX proveedor_id_empresa_idx ON public.proveedor (id_empresa);

-- =====================================================
-- 8. REGLAS DE NEGOCIO (funciones y triggers)
-- =====================================================

-- Exige fecha, sede y cantidad de asistentes al aceptar, confirmar o avanzar el evento.
CREATE FUNCTION public.validar_evento_confirmado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado IN ('aceptada', 'confirmado', 'preparacion', 'realizado') THEN
        IF NEW.fecha IS NULL
           OR NEW.sede_prevista IS NULL
           OR TRIM(NEW.sede_prevista) = ''
           OR NEW.cant_asistentes_estimada IS NULL
           OR NEW.cant_asistentes_estimada <= 0 THEN
            RAISE EXCEPTION
                'Para aceptar o confirmar el evento se requiere fecha, sede y cantidad estimada de asistentes válida.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_evento_confirmado
BEFORE INSERT OR UPDATE OF estado, fecha, sede_prevista, cant_asistentes_estimada
ON public.evento
FOR EACH ROW
EXECUTE FUNCTION public.validar_evento_confirmado();

-- Una propuesta aprobada o enviada no se cambia sin nueva revisión: si se modifica
-- cualquier dato, vuelve a pendiente_aprobacion y se borra la aprobación anterior.
CREATE FUNCTION public.reabrir_propuesta_modificada()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.estado IN ('aprobada', 'enviada')
       AND NEW.estado = OLD.estado
       AND (to_jsonb(NEW) - ARRAY['estado', 'aprobado_por', 'fecha_aprobacion', 'motivo_rechazo'])
           IS DISTINCT FROM
           (to_jsonb(OLD) - ARRAY['estado', 'aprobado_por', 'fecha_aprobacion', 'motivo_rechazo'])
    THEN
        NEW.estado := 'pendiente_aprobacion';
        NEW.aprobado_por := NULL;
        NEW.fecha_aprobacion := NULL;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reabrir_propuesta_modificada
BEFORE UPDATE ON public.propuesta
FOR EACH ROW
EXECUTE FUNCTION public.reabrir_propuesta_modificada();

COMMIT;

-- =====================================================
-- Sucursales (salones o lugares donde la empresa brinda sus servicios)
--  * sucursal: nombre y dirección de cada salón de la empresa.
--  * evento.id_sucursal: en qué salón es el evento (el cliente lo elige al reservar).
--  * La fecha se bloquea por salón: el mismo día puede haber eventos en salones distintos.
-- Va después de reservas_publicas.sql. Se puede ejecutar más de una vez.
-- =====================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.sucursal (
    id_sucursal integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre character varying(100) NOT NULL,
    direccion character varying(200),
    id_empresa integer NOT NULL,
    CONSTRAINT sucursal_pkey PRIMARY KEY (id_sucursal),
    CONSTRAINT sucursal_id_empresa_fkey FOREIGN KEY (id_empresa) REFERENCES public.empresas(id_empresa)
);
CREATE INDEX IF NOT EXISTS sucursal_id_empresa_idx ON public.sucursal (id_empresa);

ALTER TABLE public.evento ADD COLUMN IF NOT EXISTS id_sucursal integer;
ALTER TABLE public.evento DROP CONSTRAINT IF EXISTS evento_id_sucursal_fkey;
ALTER TABLE public.evento
    ADD CONSTRAINT evento_id_sucursal_fkey FOREIGN KEY (id_sucursal) REFERENCES public.sucursal(id_sucursal);

-- Un evento por día por salón (los eventos sin salón cuentan como un mismo lugar).
DROP INDEX IF EXISTS public.evento_fecha_ocupada_idx;
CREATE UNIQUE INDEX evento_fecha_ocupada_idx ON public.evento (id_empresa, COALESCE(id_sucursal, 0), fecha)
    WHERE fecha IS NOT NULL AND estado IN ('propuesta', 'confirmado', 'realizado');

COMMIT;

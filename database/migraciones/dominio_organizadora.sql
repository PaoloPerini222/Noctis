-- =====================================================
-- Ajustes al dominio de la organizadora de eventos
--  * servicio.importe_referencia: importe de referencia (punto de partida, no un precio fijo).
--  * Servicios habituales (catering, decoración, música, fotografía) para las empresas que no tienen ninguno.
--  * propuesta.condiciones_comerciales: condiciones de la oferta, aparte de las condiciones particulares acordadas.
--  * evento.estado_sede: suma 'no_disponible' (la sede puede estar pendiente de consulta, confirmada o no disponible).
--  * proveedor.telefono: obligatorio (los proveedores que ya estaban sin teléfono se conservan; al editarlos se pide).
--  * rechazo_solicitud: registro de los rechazos anteriores cuando el cliente retoma el mismo evento.
--  * El cliente puede aceptar con la sede pendiente: fecha, sede y asistentes se exigen para confirmar el encargo.
-- Se puede ejecutar más de una vez (no pisa nada). Docker no la ejecuta: las bases nuevas ya la traen en 00_schema.sql.
-- =====================================================

BEGIN;

ALTER TABLE public.servicio
    ADD COLUMN IF NOT EXISTS importe_referencia numeric(10,2);
ALTER TABLE public.servicio DROP CONSTRAINT IF EXISTS chk_servicio_importe_referencia;
ALTER TABLE public.servicio
    ADD CONSTRAINT chk_servicio_importe_referencia CHECK (importe_referencia IS NULL OR importe_referencia >= 0);

INSERT INTO public.servicio (nombre, descripcion, id_empresa)
SELECT h.nombre, h.descripcion, e.id_empresa
FROM public.empresas e
CROSS JOIN (VALUES
    ('Catering', 'Comida y bebida del evento'),
    ('Decoración', 'Ambientación y decoración de la sede'),
    ('Música', 'Música en vivo, DJ o sonido'),
    ('Fotografía', 'Fotografía y video del evento')
) AS h(nombre, descripcion)
WHERE NOT EXISTS (SELECT 1 FROM public.servicio s WHERE s.id_empresa = e.id_empresa);

ALTER TABLE public.propuesta
    ADD COLUMN IF NOT EXISTS condiciones_comerciales character varying(500);

ALTER TABLE public.evento DROP CONSTRAINT IF EXISTS chk_evento_estado_sede;
ALTER TABLE public.evento
    ADD CONSTRAINT chk_evento_estado_sede CHECK (estado_sede IN ('pendiente', 'confirmada', 'no_disponible'));

-- NOT VALID: no revisa los proveedores que ya existían, solo los que se creen o editen desde ahora.
ALTER TABLE public.proveedor DROP CONSTRAINT IF EXISTS chk_proveedor_telefono;
ALTER TABLE public.proveedor
    ADD CONSTRAINT chk_proveedor_telefono CHECK (NULLIF(TRIM(BOTH FROM telefono), '') IS NOT NULL) NOT VALID;

CREATE TABLE IF NOT EXISTS public.rechazo_solicitud (
    id_rechazo integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_evento integer NOT NULL,
    fecha_rechazo date,
    motivo character varying(500),
    total_propuesto numeric(10,2),
    fecha_reapertura timestamp with time zone NOT NULL DEFAULT now(),
    reabierto_por integer NOT NULL,
    CONSTRAINT rechazo_solicitud_pkey PRIMARY KEY (id_rechazo),
    CONSTRAINT rechazo_solicitud_id_evento_fkey FOREIGN KEY (id_evento) REFERENCES public.evento(id_evento),
    CONSTRAINT rechazo_solicitud_reabierto_por_fkey FOREIGN KEY (reabierto_por) REFERENCES public.personal(id_personal)
);

CREATE OR REPLACE FUNCTION public.validar_evento_confirmado()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado IN ('confirmado', 'preparacion', 'realizado') THEN
        IF NEW.fecha IS NULL
           OR NEW.sede_prevista IS NULL
           OR TRIM(NEW.sede_prevista) = ''
           OR NEW.cant_asistentes_estimada IS NULL
           OR NEW.cant_asistentes_estimada <= 0 THEN
            RAISE EXCEPTION
                'Para confirmar el encargo se requiere fecha, sede y cantidad estimada de asistentes válida.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

COMMIT;
